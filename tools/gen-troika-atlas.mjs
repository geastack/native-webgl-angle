#!/usr/bin/env node
// Embeds a baked glyph atlas (bake-font-atlas output) as a TypeScript module
// for the reusable native troika-three-text adapter. The alpha bitmap is
// raw DEFLATE then base64 (src/inflate.ts); the metric tables ride as
// packed strings (native-text-types.ts unpackRows), because nested array
// literals compile to code that builds every row.
import { readFileSync, writeFileSync } from 'node:fs'
import { deflateRawSync } from 'node:zlib'

// The fourth argument is the specifier the emitted module imports GlyphAtlas
// from. It defaults to the sibling path this package's own atlases use; an app
// baking its own fonts passes '@geastack/native-webgl-angle/native-text-types',
// because the generated module lives in the app and has no sibling to reach.
const [, , prefix, outPath, exportName, typesImport = './native-text-types'] = process.argv
if (!prefix || !outPath || !exportName) {
  console.error('usage: gen-troika-atlas.mjs <baked-prefix> <out.ts> <exportName> [types-import]')
  process.exit(2)
}

const meta = JSON.parse(readFileSync(`${prefix}.json`, 'utf8'))
const alpha = readFileSync(`${prefix}.bin`)
const b64 = deflateRawSync(alpha, { level: 9 }).toString('base64')
const chunks = []
for (let i = 0; i < b64.length; i += 4000) chunks.push(b64.slice(i, i + 4000))

const src = `// GENERATED by native-webgl-angle/tools/gen-troika-atlas.mjs — do not edit.
// Alpha glyph atlas + metrics for the native text renderer (ASCII ${meta.first}..${meta.first + meta.glyphs.length - 1}).
import { type GlyphAtlas, unpackRows } from '${typesImport}'

const b64: string[] = [
${chunks.map((c) => `  '${c}'`).join(',\n')}
]

export const ${exportName}: GlyphAtlas = {
  name: '${exportName}',
  atlasWidth: ${meta.atlasWidth},
  atlasHeight: ${meta.atlasHeight},
  pixelHeight: ${meta.pixelHeight},
  ascent: ${meta.ascent},
  descent: ${meta.descent},
  lineGap: ${meta.lineGap},
  first: ${meta.first},
  glyphs: unpackRows(7, '${meta.glyphs.flat().join(',')}'),
  kerning: unpackRows(3, '${meta.kerning.flat().join(',')}'),
  alphaPacked: true,
  alphaBase64: b64
}
`
writeFileSync(outPath, src)
console.log(`${outPath}: ${Math.round(src.length / 1024)}KB, ${meta.glyphs.length} glyphs, ${meta.kerning.length} kern pairs`)
